"""
Workflow Macro Compiler Reference Implementation
Demonstrates how Fusio compiles completed ReAct exploration traces into
deterministic, standalone Playwright Python scripts for zero-token re-execution.
"""

import json
from typing import Any, Dict, List


class MacroCompiler:
    """
    Translates ReAct JSON trace records into executable Python Playwright scripts.
    Replaces probabilistic LLM turns with microsecond local code execution.
    """

    def compile_trace_to_script(self, trace_steps: List[Dict[str, Any]], script_name: str = "compiled_macro") -> str:
        code_lines = [
            "#!/usr/bin/env python3",
            '"""',
            f"Autonomous Compiled Macro: {script_name}",
            "Generated by Fusio Workflow Macro Compiler.",
            "Bypasses LLM inference for deterministic zero-token execution.",
            '"""',
            "import asyncio",
            "from playwright.async_api import async_playwright",
            "",
            "async def run_workflow(headless: bool = True):",
            "    async with async_playwright() as p:",
            "        browser = await p.chromium.launch(headless=headless)",
            "        context = await browser.new_context()",
            "        page = await context.new_page()",
            "",
        ]

        for idx, step in enumerate(trace_steps, start=1):
            action = step.get("action")
            args = step.get("args", {})

            if action == "browser.navigate":
                url = args.get("url", "")
                code_lines.append(f"        # Step {idx}: Navigate to target page")
                code_lines.append(f'        await page.goto("{url}", wait_until="networkidle")')
                code_lines.append("")

            elif action == "browser.click":
                selector = args.get("selector", "")
                code_lines.append(f"        # Step {idx}: Click element")
                code_lines.append(f'        await page.click("{selector}")')
                code_lines.append("")

            elif action == "browser.type":
                selector = args.get("selector", "")
                text = args.get("text", "")
                code_lines.append(f"        # Step {idx}: Fill input field")
                code_lines.append(f'        await page.fill("{selector}", "{text}")')
                code_lines.append("")

            elif action == "browser.wait_for_selector":
                selector = args.get("selector", "")
                timeout = args.get("timeout_ms", 5000)
                code_lines.append(f"        # Step {idx}: Await selector appearance")
                code_lines.append(f'        await page.wait_for_selector("{selector}", timeout={timeout})')
                code_lines.append("")

        code_lines.extend([
            "        await context.close()",
            "        await browser.close()",
            '        print("[Macro] Execution completed successfully.")',
            "",
            'if __name__ == "__main__":',
            "    asyncio.run(run_workflow())",
        ])

        return "\n".join(code_lines)


def main():
    compiler = MacroCompiler()
    sample_trace = [
        {"action": "browser.navigate", "args": {"url": "https://example.com/portal/login"}},
        {"action": "browser.type", "args": {"selector": "#username_input", "text": "demo_user"}},
        {"action": "browser.type", "args": {"selector": "#password_input", "text": "secure_pass"}},
        {"action": "browser.click", "args": {"selector": "button#submit_btn"}},
        {"action": "browser.wait_for_selector", "args": {"selector": ".dashboard_loaded", "timeout_ms": 8000}},
    ]

    compiled_code = compiler.compile_trace_to_script(sample_trace, "portal_auto_login")
    print("Compiled Python Macro Output:\n")
    print(compiled_code)


if __name__ == "__main__":
    main()